#!/usr/bin/env python3
"""Build the GitHub Pages copy of the legend client.

The server keeps the canonical client in outputs/legend-entry/web.  The GitHub
copy is identical except for js/config.js (absolute server origin) and absolute
/assets, /audio URLs in index.html, which must point at the game server.
"""
from pathlib import Path
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "outputs/legend-entry/web"
REPO = Path("/Users/reb00t/workspace/temp/reb00t.github.io")
DST = REPO / "games/legend"
SERVER = "https://43.106.103.170.sslip.io"


def main() -> int:
    assets_backup = None
    if DST.exists():
        resolved = DST.resolve()
        assert resolved.parent == (REPO / "games").resolve(), resolved
        if (DST / "assets").exists():
            assets_backup = REPO / "games/.legend-assets-backup"
            if assets_backup.exists():
                shutil.rmtree(assets_backup)
            shutil.move(str(DST / "assets"), str(assets_backup))
        shutil.rmtree(DST)
    shutil.copytree(SRC, DST, ignore=shutil.ignore_patterns(".DS_Store"))
    if assets_backup is not None:
        shutil.move(str(assets_backup), str(DST / "assets"))
    (DST / "js/config.js").write_text(
        "// Generated by build_github_client.py\n"
        f'window.LEGEND_SERVER = "{SERVER}";\n'
        'window.LEGEND_ASSET_BASE = ".";\n'
        'window.LEGEND_ASSET_CDN = "https://reb00t-test.oss-cn-guangzhou.aliyuncs.com/legend";\n'
        "window.LEGEND_ASSET_WEBP = true;\n"
        "window.LEGEND_ASSET_MANIFEST = true;\n",
        encoding="utf-8",
    )
    page = DST / "index.html"
    html = page.read_text(encoding="utf-8")
    # Assets live beside index.html on GitHub Pages; strip the server root slash.
    html = re.sub(r'(["\'\(])/(assets|audio)/', lambda m: f'{m.group(1)}{m.group(2)}/', html)
    html = html.replace("js/config.js", "js/config.js?v=round23")
    # GitHub Pages/Fastly can fail to hand a large gzipped external script to
    # Chrome.  Inline the runtime into the page instead.
    runtime = (DST / "js/main.js").read_text(encoding="utf-8").replace("</script", "<\\/script")
    import re as _re
    html = _re.sub(r'<script src="js/main\.js\?v=[^"]+"></script>',
                   lambda _m: "<script>\n" + runtime + "\n</script>", html)
    page.write_text(html, encoding="utf-8")
    (REPO / ".nojekyll").touch()
    print(f"built {DST}")
    for p in sorted(DST.rglob("*")):
        if p.is_file() and p.suffix in {".html", ".js", ".css"}:
            print(f"  {p.relative_to(DST)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
